// [A4] Libraries used by the program:
//   <iostream> - cout for printing to the terminal
//   <fstream>  - ifstream to read the puzzle files ([Rev] and ofstream to
//                write the solution files)
//   <vector>   - vector holds the 9x9 grid and the list of puzzle file names
//   <string>   - string holds file names
//   "using namespace std" lets the code write cout instead of std::cout.
#include <iostream>
#include <fstream>
#include <vector>
#include <string>

using namespace std;

// ============================================================================
// CLASS: Sudoku
// Source : [A4] class, grid, and rule checks; [GenAI] input checks in
//          loadPuzzle() and hasValidGivens(); [Rev] printBoard() can print to
//          any stream, and loadPuzzle() also rejects extra values.
// Purpose: Stores one 9x9 board and answers questions about it, such as
//          "where is the next empty cell?" and "may this digit go here?".
// ============================================================================
class Sudoku {
private:
    // [A4] grid: 9 rows of 9 characters; '1'-'9' is a digit, '_' is empty.
    vector<vector<char>> grid;

public:
    // [A4] Constructor: resizes grid to 9 rows, each a vector of 9 chars, so
    //      every cell exists before the puzzle file is read into it.
    Sudoku() {
        grid.resize(9, vector<char>(9));
    }

    // loadPuzzle: reads the 81 values of a puzzle file into grid. Returns true
    // only when the file opened and held exactly 81 legal values.
    //   [A4]    Open the file with ifstream fin; if it did not open, print an
    //           error and return false.
    //   [A4]    The nested row/col loops read one character per cell with
    //           fin >> (the >> operator skips spaces and line breaks).
    //   [GenAI] After each read, reject the file if the read failed (the file
    //           is too short) or the character is not '_' or '1'-'9'.
    //   [Rev]   After 81 cells, try to read one more value; if that works the
    //           file has extra values, so it is rejected too.
    //   [A4]    Close the file and return true.
    bool loadPuzzle(const string& filename) {
        ifstream fin(filename);

        if (!fin) {
            cout << "Error opening file: " << filename << endl;
            return false;
        }

        for (int row = 0; row < 9; row++) {
            for (int col = 0; col < 9; col++) {
                fin >> grid[row][col];

                // [GenAI] The read failed (a value is missing) or the character
                // is neither an underscore nor a digit 1-9: report and reject.
                if (!fin || !(grid[row][col] == '_' ||
                              (grid[row][col] >= '1' && grid[row][col] <= '9'))) {
                    cout << "Invalid puzzle format in file: " << filename << endl;
                    return false;
                }
            }
        }

        // [Rev] A correct file has only spaces and line breaks after the 81st
        // value, so a successful extra read means the file has too many values.
        char extraValue;                                    // [Rev] receives an 82nd value, if any
        if (fin >> extraValue) {                            // [Rev] true only if more data exists
            cout << "Invalid puzzle format in file: " << filename << endl; // [Rev] same message as above
            return false;                                   // [Rev] reject the file
        }

        fin.close();
        return true;
    }

    // printBoard: writes the board as 9 lines of "value " - the same layout as
    // the puzzle files. [A4] wrote the loops for the terminal; [Rev] added the
    // out parameter so the same code also writes the solution files.
    //   outer loop     - one pass per row
    //   inner loop     - prints each cell's character followed by a space
    //   after each row - '\n' ends the line ([Rev] replaced endl, which also
    //                    flushed the stream after every line and was slow)
    void printBoard(ostream& out = cout) const {            // [Rev] any stream; defaults to the terminal
        for (int row = 0; row < 9; row++) {
            for (int col = 0; col < 9; col++) {
                out << grid[row][col] << " ";               // [Rev] cout -> out
            }
            out << '\n';                                    // [Rev] endl -> '\n'
        }
    }

    // [A4] findEmptyCell: scans row by row, left to right, for the first '_'.
    //   row and col are reference parameters, so the caller receives the
    //   position of the empty cell. Returns true if one was found, or false
    //   when the board is full (which means the puzzle is solved).
    bool findEmptyCell(int& row, int& col) const {

        for (row = 0; row < 9; row++) {
            for (col = 0; col < 9; col++) {

                if (grid[row][col] == '_')
                    return true;
            }
        }

        return false;
    }

    // [A4] validInRow: loops over the 9 columns of the given row and returns
    //   false if value is already there, otherwise true.
    bool validInRow(int row, char value) const {

        for (int col = 0; col < 9; col++) {
            if (grid[row][col] == value)
                return false;
        }

        return true;
    }

    // [A4] validInColumn: the same check down the 9 rows of one column.
    bool validInColumn(int col, char value) const {

        for (int row = 0; row < 9; row++) {
            if (grid[row][col] == value)
                return false;
        }

        return true;
    }

    // [A4] validInBlock: (row / 3) * 3 and (col / 3) * 3 give the top-left
    //   corner of the 3x3 block that holds the cell. The two loops visit the
    //   block's 9 cells and return false if value is already there.
    bool validInBlock(int row, int col, char value) const {

        int startRow = (row / 3) * 3;
        int startCol = (col / 3) * 3;

        for (int r = startRow; r < startRow + 3; r++) {
            for (int c = startCol; c < startCol + 3; c++) {

                if (grid[r][c] == value)
                    return false;
            }
        }

        return true;
    }

    // [A4] isValidMove: a digit may go in a cell only if it is not already in
    //   that cell's row, column, or 3x3 block (all three checks must pass).
    bool isValidMove(int row, int col, char value) const {

        return validInRow(row, value) &&
               validInColumn(col, value) &&
               validInBlock(row, col, value);
    }

    // [GenAI] hasValidGivens: checks that the numbers already in the puzzle do
    //   not break the rules (for example, two 7s in one row). Without this
    //   check the solver fills the blanks around the clash and prints an
    //   invalid "solution". Each given is hidden for a moment so isValidMove()
    //   does not compare it with itself, tested, and then put back.
    bool hasValidGivens() {

        for (int row = 0; row < 9; row++) {                 // every row
            for (int col = 0; col < 9; col++) {             // every column in that row

                char value = grid[row][col];                // the cell being checked

                if (value != '_') {                         // only givens need checking
                    grid[row][col] = '_';                   // hide the given from itself
                    bool ok = isValidMove(row, col, value); // could it legally go here?
                    grid[row][col] = value;                 // put the given back

                    if (!ok)                                // the same digit is already nearby
                        return false;                       // so the puzzle cannot be solved
                }
            }
        }

        return true;                                        // no given numbers clash
    }

    // [A4] setValue: stores a digit (or '_' to undo it) in one cell.
    // [Rev] The old getGrid() was removed: it copied the whole board for every
    //       solution, and solutions are now printed straight from the board.
    void setValue(int row, int col, char value) {
        grid[row][col] = value;
    }
};

// ============================================================================
// CLASS: SudokuSolver
// Source : [A4] recursive solve() with backtracking; [GenAI] idea of writing
//          the solutions to a file; [Rev] each solution is printed and written
//          the moment it is found, and only a counter is kept.
// Purpose: Finds EVERY solution of one puzzle with a depth-first search.
//          Each complete grid goes to the terminal and to the puzzle's
//          solutionN.txt file; printSummary() then writes the final line.
// ============================================================================
class SudokuSolver {
private:
    int solutionCount;          // [Rev] number of solutions found so far
    ostream& solutionFile;      // [Rev] the open solutionN.txt for this puzzle

public:

    // [Rev] Constructor: starts with zero solutions and remembers the stream
    //       (the puzzle's solutionN.txt) that the solutions are written to.
    SudokuSolver(ostream& fileOut)
        : solutionCount(0),         // [Rev] nothing found yet
          solutionFile(fileOut) {   // [Rev] where solutions are written
    }

    // solve: recursive depth-first search with backtracking ([A4]).
    //   1. Ask the board for the first empty cell (row, col).
    //   2. If there is none, the board is full and valid, so record it as a
    //      solution ([Rev] recordSolution() replaced storing a copy of the
    //      grid) and return to keep looking for other solutions.
    //   3. Otherwise try the digits '1' to '9' in that cell. For each legal
    //      digit: place it, call solve() again to fill the rest of the board,
    //      then reset the cell to '_' (the backtracking step) so the next digit
    //      can be tried. Trying every digit is what finds ALL the solutions.
    void solve(Sudoku& puzzle) {

        int row;
        int col;

        if (!puzzle.findEmptyCell(row, col)) {

            recordSolution(puzzle);                         // [Rev] print and write it now
            return;
        }

        for (char digit = '1'; digit <= '9'; digit++) {

            if (puzzle.isValidMove(row, col, digit)) {

                puzzle.setValue(row, col, digit);

                solve(puzzle);

                // Backtracking step
                puzzle.setValue(row, col, '_');
            }
        }
    }

    // [Rev] recordSolution: called by solve() once for every complete board.
    void recordSolution(const Sudoku& puzzle) {
        solutionCount++;                                    // count this solution
        cout << "\nSolution " << solutionCount << ":\n\n";  // terminal label, as [A4] printed it
        puzzle.printBoard(cout);                            // show the solution on the terminal
        puzzle.printBoard(solutionFile);                    // write the same 9 lines to solutionN.txt
        solutionFile << '\n';                               // blank line after each solution
    }

    // printSummary (was printSolutions() in [A4]): ends the output for one
    //   puzzle. [A4] printed "No solution found." or the number of solutions
    //   to the terminal; [Rev] also writes that line to solutionN.txt.
    void printSummary() {

        if (solutionCount == 0) {                           // [Rev] the search found nothing

            cout << "\nNo solution found.\n";
            solutionFile << "No solution found.\n";         // [Rev] the file's only line
            return;
        }

        cout << "\nSolutions found: "
             << solutionCount                               // [Rev] was solutions.size()
             << endl;
        solutionFile << "Solutions found: " << solutionCount << '\n'; // [Rev] last line of the file
    }
};

// ============================================================================
// CLASS: PuzzleManager
// Source : [A4] list of puzzle files and the loop that processes them;
//          [GenAI] givens check before solving and the "written to" message;
//          [Rev] solution file name helper, banner printed first, and a
//          solution file written even when a puzzle cannot be read.
// Purpose: Runs the whole program: for each puzzle file it prints the banner
//          and the puzzle, solves it, and fills in its solutionN.txt.
// ============================================================================
class PuzzleManager {
private:
    // [A4] names of the five puzzle files, in order
    vector<string> puzzleFiles;

    // [Rev] solutionFileName: turns "puzzleN.txt" into "solutionN.txt" by
    //   replacing the "puzzle" prefix (idea adapted from Gemini 4 Argon's
    //   answer; the [GenAI] base used substr(6), a hard-coded length). A name
    //   without the prefix gets "solution_" in front instead, so a puzzle
    //   file can never be overwritten by its own solution file.
    string solutionFileName(const string& puzzleFileName) const {
        const string prefix = "puzzle";                                  // expected start of the name
        if (puzzleFileName.compare(0, prefix.length(), prefix) == 0) {    // the name starts with "puzzle"
            return "solution" + puzzleFileName.substr(prefix.length());  // keep the "N.txt" part
        }
        return "solution_" + puzzleFileName;                              // fallback for other names
    }

public:

    // [A4] Constructor: fills the list with puzzle1.txt through puzzle5.txt.
    PuzzleManager() {

        puzzleFiles.push_back("puzzle1.txt");
        puzzleFiles.push_back("puzzle2.txt");
        puzzleFiles.push_back("puzzle3.txt");
        puzzleFiles.push_back("puzzle4.txt");
        puzzleFiles.push_back("puzzle5.txt");
    }

    // processPuzzles: handles each puzzle file in turn.
    //   [Rev]   const string& avoids copying every file name.
    //   [A4]    Print a banner with the puzzle file name.
    //   [Rev]   Create solutionN.txt before reading the puzzle, so every
    //           puzzle gets a solution file even if it cannot be read.
    //   [A4]    Load and print the puzzle ([Rev] only if it loaded).
    //   [GenAI] Solve only if the given numbers do not already break the rules.
    //   [Rev]   printSummary() writes the count or "No solution found." to the
    //           terminal and the file; then the file is closed and reported.
    void processPuzzles() {

        for (const string& filename : puzzleFiles) {

            cout << "\n================================================";
            cout << "\nPuzzle File: " << filename;
            cout << "\n================================================\n";

            string solutionName = solutionFileName(filename);           // [Rev] e.g. solution1.txt
            ofstream solutionFile(solutionName);                        // [Rev] create (or overwrite) it
            if (!solutionFile) {                                        // [Rev] it could not be created
                cout << "Error creating output file: " << solutionName << endl; // [Rev] tell the user
            }

            Sudoku puzzle;
            SudokuSolver solver(solutionFile);                          // [Rev] solver writes into the file

            if (puzzle.loadPuzzle(filename)) {                          // [Rev] was: if (!...) continue;

                cout << "\nOriginal Puzzle:\n\n";
                puzzle.printBoard();

                cout << "\nSolved Puzzle(s):\n";

                if (puzzle.hasValidGivens())                            // [GenAI] the givens obey the rules
                    solver.solve(puzzle);                               // [A4] find every solution
                else                                                    // [Rev] explain why there is none
                    cout << "\nThe given numbers break the Sudoku rules.\n";
            }

            solver.printSummary();                                      // [Rev] count or "No solution found."
            solutionFile.close();                                       // [Rev] save solutionN.txt
            if (solutionFile)                                           // [Rev] the file was saved correctly
                cout << "\nSolutions written to: " << solutionName << "\n"; // [GenAI] confirmation line

            cout << "\n";
        }
    }
};

// [A4] main: creates the PuzzleManager (which lists the five puzzle files)
//      and runs processPuzzles(); returning 0 tells the system it succeeded.
int main() {

    PuzzleManager manager;

    manager.processPuzzles();

    return 0;
}
